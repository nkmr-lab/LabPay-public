// 日 (UTC+9 ベース) で deterministic に index を 選ぶ。
// 同じ 日 は 同じ 名言、 翌日 に 切り替わる。
export function pickTodayQuote(now = new Date()) {
  // JST に 揃える (= 0:00 ちょうど に 切り替わる)
  const jst = new Date(now.getTime() + (9 * 60 + now.getTimezoneOffset()) * 60 * 1000);
  const epochDay = Math.floor(jst.getTime() / 86400000);
  return QUOTES[((epochDay % QUOTES.length) + QUOTES.length) % QUOTES.length];
}
